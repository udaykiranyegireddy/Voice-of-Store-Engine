"""Sentence-BERT/DBSCAN semantic grouping with source evidence preserved.

The organizer specified cosine-distance eps=0.15 but did not provide a
checkpoint or DBSCAN min_samples. Both are required at run time; no checkpoint
or missing clustering parameter is guessed here. Clusters are scoped to a
store so identical text from different stores remains independently reportable.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence


def read_prepared_jsonl(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()
    with path.open("r", encoding="utf-8-sig") as source_file:
        for row_number, line in enumerate(source_file, start=1):
            if not line.strip():
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as error:
                raise ValueError(f"Prepared JSONL line {row_number} is invalid JSON.") from error
            if not isinstance(record, dict):
                raise ValueError(f"Prepared JSONL line {row_number} must be an object.")
            for field in ("source_record_id", "store_id", "source", "received_at", "feedback_text", "analysis_text"):
                if not isinstance(record.get(field), str) or not record[field].strip():
                    raise ValueError(f"Prepared JSONL line {row_number} is missing a valid {field}.")
            identity = (record["source"], record["source_record_id"])
            if identity in seen:
                raise ValueError(f"Prepared JSONL line {row_number} repeats a source record ID.")
            seen.add(identity)
            records.append(record)
    if not records:
        raise ValueError("Prepared JSONL contains no records.")
    return records


def merge_prepared_inputs(paths: Sequence[Path]) -> list[dict[str, Any]]:
    """Combine channel files for cross-channel dedup without duplicate IDs."""
    merged: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()
    for path in paths:
        for record in read_prepared_jsonl(path):
            identity = (record["source"], record["source_record_id"])
            if identity in seen:
                raise ValueError(f"Source record ID {identity[1]!r} repeats across prepared files.")
            seen.add(identity)
            merged.append(record)
    return merged


def make_issue_groups(
    records: Sequence[Mapping[str, Any]],
    labels_by_index: Sequence[int],
) -> list[dict[str, Any]]:
    """Build deterministic groups and retain every input record as evidence."""
    if len(records) != len(labels_by_index):
        raise ValueError("Every input record must have exactly one DBSCAN label.")

    by_cluster: dict[tuple[str, str], list[Mapping[str, Any]]] = defaultdict(list)
    for index, (record, cluster_label) in enumerate(zip(records, labels_by_index, strict=True)):
        # DBSCAN noise is intentionally not merged into one enormous noise group.
        cluster_key = f"cluster:{cluster_label}" if cluster_label >= 0 else f"noise:{index}"
        by_cluster[(str(record["store_id"]), cluster_key)].append(record)

    groups: list[dict[str, Any]] = []
    for (_store_scope, _cluster_key), members in by_cluster.items():
        ordered = sorted(members, key=lambda item: (item["received_at"], item["source_record_id"]))
        store_id = ordered[0]["store_id"]
        record_keys = sorted(f"{member['source']}:{member['source_record_id']}" for member in ordered)
        identity = hashlib.sha256((store_id + "\0" + "\0".join(record_keys)).encode("utf-8")).hexdigest()[:24]
        groups.append({
            "issue_group_id": identity,
            "store_id": store_id,
            "member_count": len(ordered),
            "sources": sorted({member["source"] for member in ordered}),
            "first_received_at": ordered[0]["received_at"],
            "last_received_at": ordered[-1]["received_at"],
            "evidence": [dict(member) for member in ordered],
        })
    return sorted(groups, key=lambda group: (group["store_id"], group["first_received_at"], group["issue_group_id"]))


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input", required=True, type=Path, action="append",
        help="Prepared JSONL generated by prepare.py; repeat for additional channels",
    )
    parser.add_argument("--output", required=True, type=Path, help="Grouped JSONL destination under ignored data/")
    parser.add_argument("--embedding-model", required=True, help="Organizer-approved Sentence-BERT checkpoint or local path")
    parser.add_argument("--min-samples", required=True, type=int, help="DBSCAN min_samples; no value was specified in the brief")
    parser.add_argument("--eps", type=float, default=0.15, help="Cosine distance threshold specified by the R5 brief (default: 0.15)")
    parser.add_argument("--batch-size", type=int, default=64, help="Sentence-BERT inference batch size")
    return parser


def main(argv: Iterable[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    if args.min_samples < 1 or not 0 < args.eps <= 2 or args.batch_size < 1:
        print("min-samples and batch-size must be positive; cosine eps must be in (0, 2].", file=sys.stderr)
        return 2

    output_path = args.output.resolve()
    project_root = Path(__file__).resolve().parents[2]
    private_roots = (project_root / "data", project_root / "datasets", project_root / "ml" / "data")
    if not any(output_path == root or root in output_path.parents for root in private_roots):
        print("Output must be inside ignored project data/, datasets/, or ml/data/.", file=sys.stderr)
        return 2
    if output_path.exists():
        print("Output already exists; choose a new path to avoid overwriting data.", file=sys.stderr)
        return 2

    try:
        records = merge_prepared_inputs(args.input)
        from sentence_transformers import SentenceTransformer
        from sklearn.cluster import DBSCAN
    except ImportError as error:
        print("Install ml/requirements.txt in a dedicated Python 3.13 environment before deduplication.", file=sys.stderr)
        print(f"Missing dependency: {error.name}", file=sys.stderr)
        return 2
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 2

    by_store: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        by_store[record["store_id"]].append(record)

    all_groups: list[dict[str, Any]] = []
    try:
        model = SentenceTransformer(args.embedding_model)
        for store_id in sorted(by_store):
            store_records = by_store[store_id]
            if len(store_records) == 1:
                labels = [-1]
            else:
                embeddings = model.encode(
                    [record["analysis_text"] for record in store_records],
                    batch_size=args.batch_size,
                    convert_to_numpy=True,
                    normalize_embeddings=True,
                    show_progress_bar=True,
                )
                labels = DBSCAN(
                    eps=args.eps,
                    min_samples=args.min_samples,
                    metric="cosine",
                    algorithm="brute",
                ).fit_predict(embeddings).tolist()
            all_groups.extend(make_issue_groups(store_records, labels))
    except Exception as error:  # Model loading may surface library or checkpoint-specific errors.
        print(f"Embedding or clustering failed: {error}", file=sys.stderr)
        return 2

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("x", encoding="utf-8", newline="\n") as output_file:
        for group in all_groups:
            output_file.write(json.dumps(group, ensure_ascii=False) + "\n")

    duplicate_groups = sum(group["member_count"] > 1 for group in all_groups)
    print(f"Grouped {len(records)} source records into {len(all_groups)} store-scoped issue groups.")
    print(f"Groups containing multiple records: {duplicate_groups}. No classification or accuracy score was produced.")
    print(f"Output: {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
